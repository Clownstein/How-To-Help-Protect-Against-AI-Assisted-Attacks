#!/usr/bin/env python3
"""Generate every product rule file from catalog/catalog.json and data/inbound-bot-ips.

The generator is offline and deterministic: the same catalog and snapshots always
produce byte-identical output. Run ``python tools/generate.py`` after editing the
catalog or refreshing crawler feeds, and ``python tools/generate.py --check`` in CI
to confirm the committed rule files are current.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import io
import ipaddress
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG_PATH = Path("catalog") / "catalog.json"
SNAPSHOT_DIR = Path("data") / "inbound-bot-ips"

HEADER = "Generated by tools/generate.py from catalog/catalog.json. Do not edit by hand."
MATCH_TYPES = ("host", "subdomains", "label_suffix", "url_path")
TIERS = ("core", "extended", "candidate")
PROFILES = ("recommended", "full")
FEED_FORMATS = ("google-json", "amazon-html")
DEFENDER_BATCH_LIMIT = 500
CLOUDFLARE_GATEWAY_STANDARD_LIMIT = 1000
CLOUDFLARE_EXPRESSION_LIMIT = 4096
AWS_WAF_REGEX_MAX_LENGTH = 200
AWS_WAF_REGEX_PER_SET = 10

LABEL_RE = re.compile(r"^(?!-)[a-z0-9-]{1,63}(?<!-)$")
TOKEN_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 ._/_-]*$")
BROWSER_PATTERN = re.compile(
    r"^(?:mozilla|applewebkit|chrome|safari|gecko|khtml|linux|windows|macintosh|android|iphone|mobile)(?:/[\d.]+)?$",
    re.IGNORECASE,
)
PATH_RE = re.compile(r"^/[A-Za-z0-9._~/*-]*$")


class CatalogError(ValueError):
    """Raised when the catalog or a snapshot fails validation."""


@dataclass(frozen=True)
class Destination:
    value: str
    match: str
    tier: str
    provider: str
    service: str
    source: str


@dataclass(frozen=True)
class ListName:
    """A DNS name to emit in a list product, after label_suffix expansion."""

    name: str
    subdomains: bool
    destination: Destination


@dataclass(frozen=True)
class UserAgent:
    token: str
    operator: str
    purpose: str
    kind: str
    header: bool
    feed: str | None
    header_patterns: tuple[str, ...] = ()


@dataclass(frozen=True)
class Feed:
    feed_id: str
    operator: str
    tokens: tuple[str, ...]
    url: str
    fmt: str
    snapshot: str
    aggregate: bool


