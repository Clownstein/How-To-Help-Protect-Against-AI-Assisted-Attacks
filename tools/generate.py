def write_outputs(root: Path, outputs: dict[str, str]) -> None:
    for relative, content in sorted(outputs.items()):
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)


def stale_outputs(root: Path, outputs: dict[str, str]) -> list[str]:
    stale = []
    for relative, content in sorted(outputs.items()):
        path = root / relative
        if not path.is_file() or path.read_bytes().decode("utf-8") != content:
            stale.append(relative)
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root (default: this checkout)")
    parser.add_argument("--check", action="store_true", help="exit 1 if any generated file is missing or out of date")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        outputs = build_outputs(root)
    except (CatalogError, OSError, json.JSONDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    if args.check:
        stale = stale_outputs(root, outputs)
        for relative in stale:
            print(f"out of date: {relative}", file=sys.stderr)
        if stale:
            print("run: python tools/generate.py", file=sys.stderr)
            return 1
        print(f"{len(outputs)} generated files are current")
        return 0
    write_outputs(root, outputs)
    print(f"wrote {len(outputs)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
