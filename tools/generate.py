REGEX_SPECIALS = set(".^$*+?()[]{}|\\/")


def rx_escape(text: str, escape_slash: bool = False) -> str:
    out = []
    for char in text:
        if char in REGEX_SPECIALS and (char != "/" or escape_slash):
            out.append("\\" + char)
        else:
            out.append(char)
    return "".join(out)


def label_suffix_regex(suffix: str, escape_slash: bool = False) -> str:
    return "(^|\\.)[a-z0-9-]+" + rx_escape(suffix, escape_slash) + "$"


def url_path_parts(value: str) -> tuple[str, str]:
    host, _, path = value.partition("/")
    return host, "/" + path


def url_path_regex(value: str, escape_slash: bool = False) -> str:
    """Regex for the URL path only; '*' matches one path segment."""
    _, path = url_path_parts(value)
    segment = "[^\\/]+" if escape_slash else "[^/]+"
    return "^" + segment.join(rx_escape(part, escape_slash) for part in path.split("*"))


