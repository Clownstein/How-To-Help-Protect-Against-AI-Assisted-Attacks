Network = ipaddress.IPv4Network | ipaddress.IPv6Network


def feeds(catalog: dict) -> list[Feed]:
    return [
        Feed(
            item["id"], item["operator"], tuple(item["tokens"]), item["url"], item["format"],
            item["snapshot"], bool(item["aggregate"]),
        )
        for item in catalog["inbound"]["feeds"]
    ]


def parse_network(text: str) -> Network:
    text = text.strip()
    try:
        return ipaddress.ip_network(text, strict=True)
    except ValueError:
        network = ipaddress.ip_network(text, strict=False)
        raise CatalogError(f"{text} has host bits set; expected {network}") from None


def parse_google_json(payload: str) -> list[Network]:
    document = json.loads(payload)
    prefixes = document.get("prefixes")
    if not isinstance(prefixes, list):
        raise CatalogError("feed document has no prefixes array")
    networks: list[Network] = []
    for item in prefixes:
        value = item.get("ipv4Prefix") or item.get("ipv6Prefix")
        if not value:
            raise CatalogError(f"feed prefix entry without ipv4Prefix or ipv6Prefix: {item}")
        networks.append(parse_network(value))
    return networks


AMAZON_KEY_RE = re.compile(r'"(?:ipv4Prefix|ipv6Prefix|ip_prefix|ipv6_prefix)"\s*:\s*"([^"]+)"')


def parse_amazon_html(payload: str) -> list[Network]:
    """Extract prefixes from the JSON embedded in Amazon's crawler address pages."""
    values = AMAZON_KEY_RE.findall(payload)
    if not values:
        raise CatalogError("no ipv4Prefix, ipv6Prefix, ip_prefix, or ipv6_prefix keys found in page")
    return [ipaddress.ip_network(value.strip(), strict=False) for value in values]


def parse_prefix_lines(payload: str) -> list[Network]:
    networks: list[Network] = []
    for line in payload.splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            networks.append(parse_network(line))
    return networks


def load_feed_snapshot(root: Path, feed: Feed) -> list[Network]:
    path = root / SNAPSHOT_DIR / feed.snapshot
    if not path.is_file():
        raise CatalogError(f"missing snapshot {path.relative_to(root)} for feed {feed.feed_id}; run tools/refresh_feeds.py")
    payload = path.read_text(encoding="utf-8")
    if feed.snapshot.endswith(".json"):
        networks = parse_google_json(payload)
    else:
        networks = parse_prefix_lines(payload)
    if not networks:
        raise CatalogError(f"snapshot {feed.snapshot} contains no prefixes")
    return networks


def collapse(networks: list[Network]) -> tuple[list[ipaddress.IPv4Network], list[ipaddress.IPv6Network]]:
    v4 = [net for net in networks if net.version == 4]
    v6 = [net for net in networks if net.version == 6]
    return list(ipaddress.collapse_addresses(v4)), list(ipaddress.collapse_addresses(v6))


def guard_networks(catalog: dict, networks: list[Network], context: str) -> list[Network]:
    """Drop any prefix that would cover a shared inference front end."""
    guard = catalog["egress"]["observed_inference_addresses"]
    addresses = [ipaddress.ip_address(value) for value in guard["addresses"]]
    shared = [ipaddress.ip_network(value) for value in guard["shared_prefixes"]]
    kept: list[Network] = []
    for net in networks:
        hit = next((str(addr) for addr in addresses if addr.version == net.version and addr in net), None)
        if hit is None:
            hit = next(
                (str(pre) for pre in shared if pre.version == net.version and (net == pre or net.supernet_of(pre))),
                None,
            )
        if hit is not None:
            print(f"warning: {context}: dropped {net} because it covers shared inference address space {hit}", file=sys.stderr)
            continue
        kept.append(net)
    return kept


@dataclass
class FeedData:
    feed: Feed
    ipv4: list[ipaddress.IPv4Network]
    ipv6: list[ipaddress.IPv6Network]


def load_feed_data(root: Path, catalog: dict) -> list[FeedData]:
    result = []
    for feed in feeds(catalog):
        networks = guard_networks(catalog, load_feed_snapshot(root, feed), feed.feed_id)
        ipv4, ipv6 = collapse(networks)
        result.append(FeedData(feed, ipv4, ipv6))
    return result


def aggregate_networks(feed_data: list[FeedData]) -> tuple[list[ipaddress.IPv4Network], list[ipaddress.IPv6Network]]:
    networks: list[Network] = []
    for item in feed_data:
        if item.feed.aggregate:
            networks.extend(item.ipv4)
            networks.extend(item.ipv6)
    return collapse(networks)


