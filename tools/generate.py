def valid_hostname(name: str) -> bool:
    if not name or len(name) > 253 or name.endswith("."):
        return False
    labels = name.split(".")
    return len(labels) >= 2 and all(LABEL_RE.match(label) for label in labels)


def load_catalog(root: Path = ROOT) -> dict:
    with open(root / CATALOG_PATH, encoding="utf-8") as handle:
        catalog = json.load(handle)
    validate_catalog(catalog)
    return catalog


def validate_catalog(catalog: dict) -> None:
    if catalog.get("schema_version") != 1:
        raise CatalogError("catalog schema_version must be 1")
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", catalog.get("reviewed", "")):
        raise CatalogError("catalog reviewed must be an ISO date")

    egress = catalog["egress"]
    for profile in PROFILES:
        tiers = egress["profiles"].get(profile)
        if not tiers or any(tier not in TIERS for tier in tiers):
            raise CatalogError(f"profile {profile} must list known tiers")

    never_block = set(egress["never_block"])
    seen: set[str] = set()
    for entry in egress["entries"]:
        value, match, tier = entry["value"], entry["match"], entry["tier"]
        if match not in MATCH_TYPES:
            raise CatalogError(f"{value}: unknown match type {match}")
        if tier not in TIERS:
            raise CatalogError(f"{value}: unknown tier {tier}")
        for field in ("provider", "service", "source"):
            if not entry.get(field):
                raise CatalogError(f"{value}: missing {field}")
        if value in seen:
            raise CatalogError(f"duplicate egress entry {value}")
        seen.add(value)
        if match in ("host", "subdomains"):
            if not valid_hostname(value):
                raise CatalogError(f"{value}: not a valid hostname")
            if value in never_block:
                raise CatalogError(f"{value}: listed in never_block")
        elif match == "label_suffix":
            if not value.startswith("-") or not valid_hostname("x" + value):
                raise CatalogError(f"{value}: label_suffix must start with '-' and form a hostname")
            if entry.get("enumerate") != "vertex_regions":
                raise CatalogError(f"{value}: label_suffix requires enumerate=vertex_regions")
        elif match == "url_path":
            host, _, path = value.partition("/")
            if not valid_hostname(host) or not PATH_RE.match("/" + path):
                raise CatalogError(f"{value}: url_path must be host/path")

    bedrock = egress["bedrock"]
    if bedrock["tier"] not in TIERS:
        raise CatalogError("bedrock tier unknown")
    for service in bedrock["services"]:
        for host in service["hosts"]:
            if not valid_hostname(host):
                raise CatalogError(f"bedrock host {host} is not a valid hostname")
            if host in seen:
                raise CatalogError(f"duplicate egress entry {host}")
            seen.add(host)

    for region in egress["vertex_regions"]["regions"]:
        if not LABEL_RE.match(region):
            raise CatalogError(f"vertex region {region} is not a DNS label")

    for address in egress["observed_inference_addresses"]["addresses"]:
        ipaddress.ip_address(address)
    for prefix in egress["observed_inference_addresses"]["shared_prefixes"]:
        ipaddress.ip_network(prefix, strict=True)

    inbound = catalog["inbound"]
    feed_ids: set[str] = set()
    for feed in inbound["feeds"]:
        if feed["format"] not in FEED_FORMATS:
            raise CatalogError(f"feed {feed['id']}: unknown format {feed['format']}")
        if feed["id"] in feed_ids:
            raise CatalogError(f"duplicate feed {feed['id']}")
        if not feed["url"].startswith("https://"):
            raise CatalogError(f"feed {feed['id']}: url must be https")
        feed_ids.add(feed["id"])

    tokens: set[str] = set()
    for agent in inbound["user_agents"]:
        token = agent["token"]
        if not TOKEN_RE.match(token) or " " in token:
            raise CatalogError(f"user agent token {token!r} is not a single product token")
        if token.lower() in tokens:
            raise CatalogError(f"duplicate user agent token {token}")
        tokens.add(token.lower())
        if agent["feed"] is not None and agent["feed"] not in feed_ids:
            raise CatalogError(f"user agent {token}: unknown feed {agent['feed']}")
        if agent["purpose"] not in ("training", "search", "user", "ads"):
            raise CatalogError(f"user agent {token}: unknown purpose {agent['purpose']}")
        if agent["kind"] not in ("documented", "common"):
            raise CatalogError(f"user agent {token}: unknown kind {agent['kind']}")
        patterns = agent.get("header_patterns", [])
        if not isinstance(patterns, list):
            raise CatalogError(f"user agent {token}: header_patterns must be a list")
        if patterns and not agent["header"]:
            raise CatalogError(f"user agent {token}: header_patterns require header matching")
        for pattern in patterns:
            validate_header_pattern(token, pattern)

    for token in inbound["community_robots_tokens"]["tokens"]:
        if not TOKEN_RE.match(token):
            raise CatalogError(f"community token {token!r} contains unsupported characters")

    sid_base = catalog["suricata"]["sid_base"]
    bases = sorted(sid_base.values())
    for low, high in zip(bases, bases[1:]):
        if high - low < 100000:
            raise CatalogError("suricata sid_base ranges must be at least 100000 apart")

    validate_provider_network(catalog, "anthropic_network", "AP-2440")
    validate_provider_network(catalog, "openai_network", "OOL-15")
    validate_provider_network(catalog, "xai_network", "XAI")


def validate_header_pattern(token: str, pattern: str) -> None:
    if not isinstance(pattern, str) or len(pattern) < 4:
        raise CatalogError(f"user agent {token}: header pattern {pattern!r} is shorter than 4 characters")
    if any(character in pattern for character in '#\r\n";'):
        raise CatalogError(f"user agent {token}: header pattern {pattern!r} contains a character the rules cannot quote")
    if BROWSER_PATTERN.match(pattern):
        raise CatalogError(f"user agent {token}: header pattern {pattern!r} is a browser token")


def validate_provider_network(catalog: dict, key: str, org_handle: str) -> None:
    """Reject an inventory entry that would emit an excluded allocation."""
    network = catalog[key]
    if network.get("org_handle") != org_handle:
        raise CatalogError(f"{key} org_handle must be {org_handle}")
    excluded = [ipaddress.ip_network(value, strict=True) for value in network["do_not_emit"]]
    emitted: list[Network] = []
    for item in network["prefixes"]:
        if not item.get("source", "").startswith("https://"):
            raise CatalogError(f"{item.get('prefix')}: {key} source must be https")
        prefix = ipaddress.ip_network(item["prefix"], strict=True)
        if not item["emit"]:
            continue
        emitted.append(prefix)
        for banned in excluded:
            if prefix.version == banned.version and (prefix == banned or prefix.supernet_of(banned)):
                raise CatalogError(f"{prefix} covers excluded prefix {banned}")
    if not emitted:
        raise CatalogError(f"{key} has no emitted prefixes")


def destinations(catalog: dict, profile: str) -> list[Destination]:
    egress = catalog["egress"]
    tiers = egress["profiles"][profile]
    result: list[Destination] = []
    bedrock = egress["bedrock"]
    bedrock_destinations = [
        Destination(host, "host", bedrock["tier"], bedrock["provider"], service["service"], service["source"])
        for service in bedrock["services"]
        for host in service["hosts"]
    ]
    for tier in TIERS:
        if tier not in tiers:
            continue
        for entry in egress["entries"]:
            if entry["tier"] == tier:
                result.append(
                    Destination(
                        entry["value"], entry["match"], tier, entry["provider"], entry["service"], entry["source"]
                    )
                )
        if bedrock["tier"] == tier:
            result.extend(bedrock_destinations)
    return result


def vertex_hosts(catalog: dict, suffix: str) -> list[str]:
    return [region + suffix for region in catalog["egress"]["vertex_regions"]["regions"]]


def list_names(catalog: dict, dests: list[Destination]) -> list[ListName]:
    """Flatten destinations into DNS names; label_suffix entries become enumerated hosts."""
    names: list[ListName] = []
    seen: set[str] = set()
    for dest in dests:
        if dest.match == "host":
            candidates = [(dest.value, False)]
        elif dest.match == "subdomains":
            candidates = [(dest.value, True)]
        elif dest.match == "label_suffix":
            candidates = [(host, False) for host in vertex_hosts(catalog, dest.value)]
        else:
            continue
        for name, subdomains in candidates:
            if name not in seen:
                seen.add(name)
                names.append(ListName(name, subdomains, dest))
    return names


def covered_by(name: str, parents: set[str]) -> bool:
    """True when a proper parent domain of name is present in parents."""
    labels = name.split(".")
    return any(".".join(labels[index:]) in parents for index in range(1, len(labels) - 1))


def suffix_names(names: list[ListName]) -> list[ListName]:
    """Names for products whose entries always include subdomains, with redundant children removed."""
    all_names = {item.name for item in names}
    return [item for item in names if not covered_by(item.name, all_names)]


def pattern_destinations(dests: list[Destination], match: str) -> list[Destination]:
    return [dest for dest in dests if dest.match == match]


def label(dest: Destination) -> str:
    if dest.service.lower().startswith(dest.provider.lower()):
        return dest.service
    return f"{dest.provider} {dest.service}"


