def cloudflare_expressions(catalog: dict) -> list[str]:
    clauses = [f'(lower(http.user_agent) contains "{token.lower()}")' for token in header_tokens(catalog)]
    parts: list[list[str]] = []
    current: list[str] = []
    for clause in clauses:
        candidate = "\nor ".join(current + [clause])
        if current and len(candidate) + 1 > CLOUDFLARE_EXPRESSION_LIMIT:
            parts.append(current)
            current = [clause]
        else:
            current.append(clause)
    if current:
        parts.append(current)
    expressions = []
    for part in parts:
        expression = "\nor ".join(part)
        if len(expression) + 1 > CLOUDFLARE_EXPRESSION_LIMIT:
            raise CatalogError(f"Cloudflare expression is {len(expression)} characters; limit is {CLOUDFLARE_EXPRESSION_LIMIT}")
        expressions.append(expression + "\n")
    return expressions or ["\n"]


def aws_waf_regex_pattern_sets(catalog: dict) -> list[str]:
    pieces = [rx_escape(token.lower()) for token in header_tokens(catalog)]
    sets: list[list[str]] = [[]]
    current = ""
    for piece in pieces:
        if len(piece) > AWS_WAF_REGEX_MAX_LENGTH:
            raise CatalogError(f"AWS WAF regex piece exceeds {AWS_WAF_REGEX_MAX_LENGTH} characters")
        candidate = piece if not current else current + "|" + piece
        if current and len(candidate) > AWS_WAF_REGEX_MAX_LENGTH:
            if len(sets[-1]) >= AWS_WAF_REGEX_PER_SET:
                sets.append([])
            sets[-1].append(current)
            current = piece
        else:
            current = candidate
    if current:
        if len(sets[-1]) >= AWS_WAF_REGEX_PER_SET:
            sets.append([])
        sets[-1].append(current)
    return [lines(part) for part in sets if part] or ["\n"]


