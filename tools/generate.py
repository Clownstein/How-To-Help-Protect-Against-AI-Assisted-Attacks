def provider_network_file(catalog: dict, key: str) -> str:
    """Registry-confirmed prefixes for one provider, collapsed, with exclusions omitted."""
    network = catalog[key]
    emitted = [ipaddress.ip_network(item["prefix"], strict=True) for item in network["prefixes"] if item["emit"]]
    ipv4, ipv6 = collapse(emitted)
    return commented("#", [str(net) for net in ipv4 + ipv6], network["notes"])


def lines(items: list[str]) -> str:
    return "\n".join(items) + "\n" if items else ""


def commented(prefix: str, body: list[str], extra: list[str] | None = None) -> str:
    head = [f"{prefix} {HEADER}"]
    for note in extra or []:
        head.append(f"{prefix} {note}" if note else prefix)
    return lines(head + body)


def profile_suffix(profile: str) -> str:
    return "" if profile == "recommended" else "-full"


def csv_text(rows: list[list[str]]) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerows(rows)
    return buffer.getvalue()


