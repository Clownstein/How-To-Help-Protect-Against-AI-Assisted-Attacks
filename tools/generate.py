def suricata_msg(text: str) -> str:
    return re.sub(r'[;"\\]', " ", text)


SID_SPACE = 99999


def suricata_sid_map(catalog: dict) -> dict[tuple[str, str], int]:
    """SID offsets derived from a hash of each entry, so adding entries never renumbers existing rules.

    Collisions are resolved by linear probing in sorted key order, which keeps the result
    independent of catalog ordering.
    """
    return stable_offsets({(dest.match, dest.value) for dest in destinations(catalog, "full")})


def stable_offsets(keys: set[tuple[str, str]]) -> dict[tuple[str, str], int]:
    offsets: dict[tuple[str, str], int] = {}
    used: set[int] = set()
    for key in sorted(keys):
        digest = hashlib.sha256(f"{key[0]}:{key[1]}".encode("utf-8")).digest()
        offset = int.from_bytes(digest[:8], "big") % SID_SPACE + 1
        while offset in used:
            offset = offset % SID_SPACE + 1
        used.add(offset)
        offsets[key] = offset
    return offsets


def suricata_host_rule(proto: str, buffer: str, direction: str, flow: str | None, sid: int, rev: int,
                       msg: str, content: str, pcre: str, tier: str) -> str:
    parts = [f'msg:"{suricata_msg(msg)}"']
    if flow:
        parts.append(f"flow:{flow}")
    parts.append(f"{buffer}")
    parts.append(f'content:"{content}"')
    if buffer != "http.host":
        parts.append("nocase")
    parts.append("fast_pattern")
    parts.append(f'pcre:"/{pcre}/i"')
    parts.append("classtype:policy-violation")
    parts.append(f"metadata:tier {tier}")
    parts.append(f"sid:{sid}")
    parts.append(f"rev:{rev}")
    return f"alert {proto} {direction} (" + "; ".join(parts) + ";)"


def suricata_match(dest: Destination) -> tuple[str, str]:
    """Return (content, pcre) for a host, subdomains, or label_suffix destination."""
    if dest.match == "host":
        return dest.value, "(?:^|\\.)" + rx_escape(dest.value, escape_slash=True) + "$"
    if dest.match == "subdomains":
        return "." + dest.value, "\\." + rx_escape(dest.value, escape_slash=True) + "$"
    if dest.match == "label_suffix":
        return dest.value, "[a-z0-9-]" + rx_escape(dest.value, escape_slash=True) + "$"
    raise CatalogError(f"no host match for {dest.match}")


def suricata_egress_rules(catalog: dict, dests: list[Destination], profile: str) -> str:
    sid_base = catalog["suricata"]["sid_base"]
    rev = catalog["suricata"]["rev"]
    offsets = suricata_sid_map(catalog)
    out = [
        f"# {HEADER}",
        f"# Suricata 7+ egress rules for hosted AI inference, profile: {profile}.",
        "# Rules alert by default. Convert to drop with suricata-update drop.conf (re:AI-INFERENCE) in IPS mode.",
        "",
        "# TLS SNI",
    ]
    host_dests = [dest for dest in dests if dest.match in ("host", "subdomains", "label_suffix")]
    for dest in host_dests:
        content, pcre = suricata_match(dest)
        out.append(suricata_host_rule(
            "tls", "tls.sni", "$HOME_NET any -> $EXTERNAL_NET any", "established,to_server",
            sid_base["tls_sni"] + offsets[(dest.match, dest.value)], rev,
            f"AI-INFERENCE TLS SNI {dest.provider} {dest.value}", content, pcre, dest.tier,
        ))
    out.append("")
    out.append("# DNS query")
    for dest in host_dests:
        content, pcre = suricata_match(dest)
        out.append(suricata_host_rule(
            "dns", "dns.query", "$HOME_NET any -> any any", None,
            sid_base["dns_query"] + offsets[(dest.match, dest.value)], rev,
            f"AI-INFERENCE DNS query {dest.provider} {dest.value}", content, pcre, dest.tier,
        ))
    out.append("")
    out.append("# HTTP Host (plaintext HTTP or decrypted traffic)")
    for dest in host_dests:
        content, pcre = suricata_match(dest)
        out.append(suricata_host_rule(
            "http", "http.host", "$HOME_NET any -> $EXTERNAL_NET any", "established,to_server",
            sid_base["http_host"] + offsets[(dest.match, dest.value)], rev,
            f"AI-INFERENCE HTTP Host {dest.provider} {dest.value}", content, pcre, dest.tier,
        ))
    for dest in pattern_destinations(dests, "url_path"):
        host, _ = url_path_parts(dest.value)
        sid = sid_base["http_host"] + offsets[(dest.match, dest.value)]
        path_pcre = url_path_regex(dest.value, escape_slash=True)
        parts = [
            f'msg:"{suricata_msg("AI-INFERENCE HTTP path " + dest.provider + " " + dest.value)}"',
            "flow:established,to_server",
            "http.host",
            f'content:"{host}"',
            f'pcre:"/^{rx_escape(host, escape_slash=True)}$/i"',
            "http.uri",
            f'pcre:"/{path_pcre}/"',
            "classtype:policy-violation",
            f"metadata:tier {dest.tier}",
            f"sid:{sid}",
            f"rev:{rev}",
        ]
        out.append("alert http $HOME_NET any -> $EXTERNAL_NET any (" + "; ".join(parts) + ";)")
    return lines(out)


def suricata_crawler_rules(catalog: dict) -> str:
    sid_base = catalog["suricata"]["sid_base"]["http_user_agent"]
    rev = catalog["suricata"]["rev"]
    out = [
        f"# {HEADER}",
        "# Suricata 7+ inbound rules for AI crawler user-agent tokens sent to your published services.",
        "# User-agent strings are self-asserted; pair these rules with the address feeds in rules/ip-feeds.",
        "",
    ]
    agents = [agent for agent in user_agents(catalog) if agent.header]
    pattern_owner: dict[str, UserAgent] = {}
    for agent in agents:
        for pattern in header_match_patterns(agent):
            pattern_owner.setdefault(pattern.lower(), agent)
    offsets = stable_offsets({("user_agent", pattern) for pattern in pattern_owner})
    for pattern in sorted(pattern_owner):
        agent = pattern_owner[pattern]
        index = offsets[("user_agent", pattern)]
        parts = [
            f'msg:"{suricata_msg(f"AI-CRAWLER User-Agent {agent.token} ({agent.operator})")}"',
            "flow:established,to_server",
            "http.user_agent",
            f'content:"{pattern}"',
            "nocase",
            "classtype:policy-violation",
            f"metadata:purpose {agent.purpose}",
            f"sid:{sid_base + index}",
            f"rev:{rev}",
        ]
        out.append("alert http $EXTERNAL_NET any -> $HOME_NET any (" + "; ".join(parts) + ";)")
    return lines(out)


