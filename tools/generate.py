def palo_alto_url_edl(catalog: dict, dests: list[Destination]) -> str:
    entries = []
    for item in list_names(catalog, dests):
        entries.append(("*." if item.subdomains else "") + item.name + "/")
    for dest in pattern_destinations(dests, "url_path"):
        entries.append(dest.value)
    return lines(entries)


def zscaler_urls(catalog: dict, dests: list[Destination]) -> str:
    return lines([("." if item.subdomains else "") + item.name for item in list_names(catalog, dests)])


def netskope_urls(catalog: dict, dests: list[Destination], profile: str) -> str:
    body = [("*." if item.subdomains else "") + item.name for item in list_names(catalog, dests)]
    return commented("#", body, [f"Netskope exact/wildcard URL list, profile: {profile}."])


def netskope_regex(dests: list[Destination]) -> str:
    body = []
    for dest in pattern_destinations(dests, "label_suffix"):
        body.append("^[a-z0-9-]+" + rx_escape(dest.value) + "(:[0-9]+)?(/|$)")
    for dest in pattern_destinations(dests, "url_path"):
        host, _ = url_path_parts(dest.value)
        body.append("^" + rx_escape(host) + "(:[0-9]+)?" + url_path_regex(dest.value)[1:])
    return commented("#", body, ["Netskope regex URL list (PCRE, no scheme)."])


def cloudflare_gateway_csv(catalog: dict, dests: list[Destination]) -> str:
    rows = [["value", "description"]]
    for item in suffix_names(list_names(catalog, dests)):
        rows.append([item.name, label(item.destination)])
    return csv_text(rows)


def umbrella_destinations(catalog: dict, dests: list[Destination]) -> str:
    return lines([item.name for item in suffix_names(list_names(catalog, dests))])


def squid_domains(catalog: dict, dests: list[Destination], profile: str) -> str:
    body = ["." + item.name for item in suffix_names(list_names(catalog, dests))]
    return commented("#", body, [f"Squid dstdomain / ssl::server_name list, profile: {profile}."])


def squid_domain_regex(dests: list[Destination]) -> str:
    body = [label_suffix_regex(dest.value) for dest in pattern_destinations(dests, "label_suffix")]
    return commented("#", body, ["Squid dstdom_regex / ssl::server_name_regex list. Use with -i."])


def squid_url_regex(dests: list[Destination]) -> str:
    body = []
    for dest in pattern_destinations(dests, "url_path"):
        host, _ = url_path_parts(dest.value)
        body.append("^https?://" + rx_escape(host) + "(:[0-9]+)?" + url_path_regex(dest.value)[1:])
    return commented("#", body, ["Squid url_regex list. Matches only requests Squid can see in full (HTTP or bumped HTTPS)."])


def tmsh_quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def f5_datagroups(catalog: dict, dests: list[Destination], profile: str) -> str:
    names = list_names(catalog, dests)
    exact = [item for item in names if not item.subdomains]
    suffixes = [item for item in names if item.subdomains]
    patterns = pattern_destinations(dests, "label_suffix")
    paths = pattern_destinations(dests, "url_path")

    out = [f"# {HEADER}", f"# Profile: {profile}. Load with: tmsh load sys config merge file <path-to-this-file>", ""]

    def group(name: str, records: list[tuple[str, str]]) -> None:
        out.append(f"ltm data-group internal {name} {{")
        out.append("    records {")
        for key, data in records:
            out.append(f"        {tmsh_quote(key)} {{")
            out.append(f"            data {tmsh_quote(data)}")
            out.append("        }")
        out.append("    }")
        out.append("    type string")
        out.append("}")

    group("ai_inference_hosts", [(item.name, label(item.destination)) for item in exact])
    group("ai_inference_suffixes", [("." + item.name, label(item.destination)) for item in suffixes])
    group("ai_inference_label_suffixes", [(dest.value, label(dest)) for dest in patterns])
    group("ai_inference_url_paths", [(dest.value, label(dest)) for dest in paths])
    return lines(out)


def rpz_zone(catalog: dict, dests: list[Destination], profile: str) -> str:
    serial = catalog["reviewed"].replace("-", "") + "01"
    out = [
        f"; {HEADER}",
        f"; Response policy zone, profile: {profile}. CNAME . returns NXDOMAIN to the client.",
        "$TTL 300",
        f"@ IN SOA localhost. hostmaster.localhost. ( {serial} 3600 600 86400 300 )",
        "@ IN NS localhost.",
    ]
    for item in list_names(catalog, dests):
        out.append(f"; {label(item.destination)}")
        if not item.subdomains:
            out.append(f"{item.name} CNAME .")
        out.append(f"*.{item.name} CNAME .")
    return lines(out)


def pihole_adlist(catalog: dict, dests: list[Destination], profile: str) -> str:
    body = ["||" + item.name + "^" for item in suffix_names(list_names(catalog, dests))]
    head = [f"! {HEADER}", f"! Pi-hole v6 ABP-style adlist, profile: {profile}. Each entry blocks the domain and its subdomains."]
    return lines(head + body)


def pihole_domains(catalog: dict, dests: list[Destination], profile: str) -> str:
    body = [item.name for item in suffix_names(list_names(catalog, dests))]
    return commented("#", body, [f"Domains for 'pihole --wild', profile: {profile}. Read by install.sh."])


def pihole_regex(dests: list[Destination]) -> str:
    body = [label_suffix_regex(dest.value) for dest in pattern_destinations(dests, "label_suffix")]
    return commented("#", body, ["POSIX ERE filters for 'pihole --regex'. Read by install.sh."])


